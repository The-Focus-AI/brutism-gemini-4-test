export function createBuildingFromArchetype(
  archetype: BuildingArchetype,
  gridX: number,
  gridZ: number,
  rotation: number = 0,
  overrides: Partial<BuildingParams> = {}
): BuildingParams {
  const preset = ARCHETYPE_PRESETS[archetype];
  return {
    id: `bld_${Date.now()}_${Math.random().toString(36).slice(2, 7)}`,
    gridX,
    gridZ,
    rotation,
    ...structuredClone(preset.defaults),
    ...overrides,
  };
}

